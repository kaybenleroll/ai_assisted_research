out <- Sys.getenv('EXAMPLE_OUT', unset=tempdir())
check_sha256 <- function(path, expected) {
  actual <- strsplit(system2('sha256sum', shQuote(path), stdout=TRUE), ' +')[[1]][1]
  stopifnot(identical(actual, expected))
}
